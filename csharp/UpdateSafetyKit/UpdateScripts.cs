using System;
using System.Collections.Generic;
using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;

namespace UpdateSafetyKit;

/// <summary>
/// A generated Windows script plus the environment variables it reads. The script itself is ASCII only; every path travels in an
/// environment variable, so install folders and %TEMP% under non-ASCII user names (e.g. C:\Users\田中) work.
/// <para>生成した手順（cmd）と、それが読む環境変数。手順は ASCII だけで、パスは全部環境変数で渡すので、日本語の利用者名の下でも動く。</para>
/// </summary>
public sealed record ScriptPlan(string Script, IReadOnlyDictionary<string, string> Environment);

/// <summary>
/// Builds the apply / rollback scripts (cmd + robocopy, no deletion inside the app folder, user-data folders excluded).
/// <para>適用・戻しの手順を作る（cmd と robocopy。実行フォルダの中は 1 つも消さない。利用者データのフォルダは除く）。</para>
/// </summary>
public static class UpdateScripts
{
    /// <summary>
    /// Apply script: wait for the app to exit → delete the previous backup (only the sibling "&lt;app&gt;&lt;PrevSuffix&gt;") →
    /// copy the current version there → overwrite the app folder with the staging folder → start the app.
    /// If the backup copy fails, nothing is overwritten. If the overwrite fails, the backup is copied back.
    /// <para>適用: 終了待ち → 前の控えを消す（隣の控えだけ）→ 今の版を写す → 新しい版で上書き → 起動。写せなければ上書きしない。上書きに失敗したら控えから戻す。</para>
    /// </summary>
    public static ScriptPlan BuildApply(UpdateSafetyOptions o, int pid, string stagingDir, string appDir, string exeName)
    {
        var app = Norm(appDir); var stg = Norm(stagingDir);
        var prev = CrashWatch.PrevDirFor(o, app);
        Guard(app, prev, stg, exeName);
        var p = o.ScriptEnvPrefix;
        var sb = Header(pid, "auto-update apply script");
        sb.Append("rem keep exactly one previous generation next to the app folder\r\n");
        sb.Append($"if exist \"%{p}PREV%\\\" rd /s /q \"%{p}PREV%\"\r\n");
        sb.Append($"robocopy \"%{p}APP%\" \"%{p}PREV%\" /E /XJ /R:3 /W:1{Xd(o, p + "APP")} >nul\r\n");
        sb.Append("if errorlevel 8 goto prevfail\r\n");
        sb.Append($"robocopy \"%{p}STAGING%\" \"%{p}APP%\" /E /R:3 /W:1{Xd(o, p + "STAGING")} >nul\r\n");
        sb.Append("if errorlevel 8 goto applyfail\r\n");
        Launch(o, sb, p);
        sb.Append("exit /b 0\r\n");
        sb.Append(":applyfail\r\n");
        sb.Append($"robocopy \"%{p}PREV%\" \"%{p}APP%\" /E /R:3 /W:1{Xd(o, p + "PREV")} >nul\r\n");
        sb.Append(":prevfail\r\n");
        Launch(o, sb, p);
        sb.Append("exit /b 1\r\n");
        return Plan(sb, p, ("APP", app), ("PREV", prev), ("STAGING", stg), ("EXE", exeName));
    }

    /// <summary>
    /// Rollback script: wait for the app to exit → stop processes running from inside the app folder → copy the backup over the
    /// app folder (user data excluded, nothing deleted) → start the app. Note: files that exist only in the new version stay.
    /// <para>戻し: 終了待ち → 実行フォルダの中で動く残りを止める → 控えで上書き（利用者データは除く・何も消さない）→ 起動。
    /// 新しい版にだけあるファイルは残る。</para>
    /// </summary>
    public static ScriptPlan BuildRollback(UpdateSafetyOptions o, int pid, string appDir, string exeName)
    {
        var app = Norm(appDir);
        var prev = CrashWatch.PrevDirFor(o, app);
        Guard(app, prev, null, exeName);
        var p = o.ScriptEnvPrefix;
        var sb = Header(pid, "auto-rollback script");
        sb.Append("powershell -NoProfile -NonInteractive -Command \"Get-Process | Where-Object { $_.Path -and $_.Path.StartsWith($env:")
          .Append(p).Append("APP + '\\', [System.StringComparison]::OrdinalIgnoreCase) } | Stop-Process -Force -ErrorAction SilentlyContinue\"\r\n");
        sb.Append($"robocopy \"%{p}PREV%\" \"%{p}APP%\" /E /R:5 /W:2{Xd(o, p + "PREV")} >nul\r\n");
        sb.Append("if errorlevel 8 goto fail\r\n");
        Launch(o, sb, p);
        sb.Append("exit /b 0\r\n");
        sb.Append(":fail\r\n");
        Launch(o, sb, p);
        sb.Append("exit /b 1\r\n");
        return Plan(sb, p, ("APP", app), ("PREV", prev), ("EXE", exeName));
    }

    private static StringBuilder Header(int pid, string what)
    {
        if (pid <= 0) throw new ArgumentException("pid must be positive");
        var sb = new StringBuilder();
        sb.Append("@echo off\r\n");
        sb.Append("setlocal DisableDelayedExpansion\r\n");
        sb.Append("rem ").Append(what).Append(" (generated by UpdateSafetyKit; ASCII only; paths come from environment variables)\r\n");
        sb.Append("powershell -NoProfile -NonInteractive -Command \"Wait-Process -Id ").Append(pid.ToString(CultureInfo.InvariantCulture)).Append(" -ErrorAction SilentlyContinue\"\r\n");
        return sb;
    }

    private static void Launch(UpdateSafetyOptions o, StringBuilder sb, string p)
    {
        if (o.LaunchAfterScript) sb.Append($"start \"\" \"%{p}APP%\\%{p}EXE%\"\r\n");
    }

    private static string Xd(UpdateSafetyOptions o, string rootVar)
    {
        if (o.MutableDirs.Count == 0) return "";
        var sb = new StringBuilder(" /XD");
        foreach (var d in o.MutableDirs) sb.Append(" \"%").Append(rootVar).Append("%\\").Append(d.Replace('/', '\\').Trim('\\')).Append('"');
        return sb.ToString();
    }

    private static ScriptPlan Plan(StringBuilder sb, string prefix, params (string Key, string Value)[] env)
    {
        var s = sb.ToString();
        foreach (var ch in s) if (ch > 127) throw new InvalidOperationException("generated script must be ASCII only");
        var d = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var (k, v) in env) d[prefix + k] = v;
        return new ScriptPlan(s, d);
    }

    private static string Norm(string p) => (p ?? "").TrimEnd('\\', '/');

    private static readonly Regex WinAbs = new(@"^([A-Za-z]:\\|\\\\[^\\/]+\\[^\\/]+)", RegexOptions.CultureInvariant);

    // Paths are expanded by cmd inside double quotes only, so the only characters that can break out are '"' and line breaks.
    // ('%' and '!' in a value are not re-expanded: expansion is single-pass and delayed expansion is disabled.)
    private static void Guard(string appDir, string prevDir, string? stagingDir, string exeName)
    {
        foreach (var x in new[] { appDir, prevDir, stagingDir ?? @"C:\x", exeName })
            if (x.IndexOfAny(new[] { '"', '\r', '\n', '\0' }) >= 0) throw new ArgumentException("path contains a character that cannot be used in the script");
        if (!WinAbs.IsMatch(appDir) || !WinAbs.IsMatch(prevDir) || (stagingDir is not null && !WinAbs.IsMatch(stagingDir)))
            throw new ArgumentException("paths must be absolute Windows paths (C:\\... or \\\\server\\share\\...)");
        if (exeName.Length == 0 || exeName.IndexOfAny(new[] { '\\', '/', ':' }) >= 0) throw new ArgumentException("exeName must be a file name");
        if (stagingDir is not null)
        {
            var a = appDir + "\\"; var s = stagingDir + "\\";
            if (s.StartsWith(a, StringComparison.OrdinalIgnoreCase) || a.StartsWith(s, StringComparison.OrdinalIgnoreCase))
                throw new ArgumentException("stagingDir must not be inside the app folder (or contain it)");
        }
    }
}
